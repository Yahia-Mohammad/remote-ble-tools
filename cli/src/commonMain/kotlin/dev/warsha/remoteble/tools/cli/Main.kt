private class ObserveCommand(root: RootCommand) : CharacteristicCommand(root, "observe", "Stream bounded characteristic notifications.") {
    private val count: Int? by option("--count", help = "Maximum notifications to emit.").int()
    private val timeout: String? by option("--timeout", help = "Stream deadline.")
    private val unbounded: Boolean by option("--unbounded", help = "Use only when local policy explicitly permits an unbounded stream.").flag()

    override fun run() = execute {
        val limit = count
        val deadline = timeout
        if (limit != null && limit <= 0) throw CliFailure(ExitCode.USAGE, "--count must be positive")
        if (limit != null && limit > root.config().policy.maximumNotificationCount) {
            throw CliFailure(ExitCode.UNSUPPORTED, "--count exceeds local policy limit of ${root.config().policy.maximumNotificationCount}")
        }
        if (unbounded && (limit != null || deadline != null)) throw CliFailure(ExitCode.USAGE, "--unbounded cannot be combined with --count or --timeout")
        if (limit == null && deadline == null && (!unbounded || !root.config().policy.allowUnboundedStreams)) {
            throw CliFailure(ExitCode.USAGE, "observe requires --count or --timeout unless local policy allows unbounded streams")
        }
        if (root.outputMode() == "json") throw CliFailure(ExitCode.USAGE, "observe uses --jsonl for structured streaming output")
        val selected = characteristic()
        var sequence = 0L
        root.gateway { gateway ->
            val stream = RemoteOperationService(gateway, root.resolvedConfig().agent.endpoint, root.auditLogger())
                .managedObserve(selected.handle, selected.service, selected.characteristic)
            var result = "complete"
            suspend fun emitNotification(value: ByteArray) {
                sequence += 1
                if (root.outputMode() == "jsonl") {
                    root.emit(
                        "observe.notification",
                        buildJsonObject {
                            put("sequence", sequence)
                            put("timestamp", Clock.System.now().toString())
                            put("handle", selected.handle)
                            put("serviceUuid", selected.service)
                            put("characteristicUuid", selected.characteristic)
                            put("value", bytesJson(value))
                        },
                        value.hex(),
                        value.hex(),
                    )
                } else {
                    root.emitBytes("observe.notification", value)
                }
            }
            try {
                result = collectBoundedStream(
                    stream.events,
                    limit,
                    deadline?.let(Duration::parse),
                    ::emitNotification,
                ).reason.auditResult
            } catch (error: Throwable) {
                result = "error"
                throw error
            } finally {
                kotlinx.coroutines.withContext(kotlinx.coroutines.NonCancellable) { runCatching { stream.stopAndAwait(result) } }
            }
        }
    }
}

private class WriteCommand(root: RootCommand) : CharacteristicCommand(root, "write", "Write a characteristic only when agent-side enforcement is negotiated.") {
    private val hexPayload: String? by option("--hex", help = "Payload as hexadecimal bytes.")
    private val base64Payload: String? by option("--base64", help = "Payload as Base64 bytes.")
    private val textPayload: String? by option("--text", help = "Payload as UTF-8 text.")
    private val stdinEncoding: String? by option("--stdin", help = "Read stdin using this explicit encoding.").choice("hex", "base64", "text")
    private val writeType: String by option("--write-type", help = "BLE write acknowledgement behavior.").choice("with-response", "without-response").required()

    override fun run() = execute {
        if (root.tokenFromStdinSelected() && stdinEncoding != null) {
            throw CliFailure(ExitCode.USAGE, "--token-stdin cannot be combined with stdin write payload")
        }
        val parsedPayload = payload()
        val selected = characteristic()
        val withResponse = writeType == "with-response"
        val endpoint = root.resolvedConfig().agent.endpoint
        root.gateway { gateway ->
            WriteOperationService(gateway, root.config().policy, endpoint, root.auditLogger()).execute(
                WriteOperationService.Request(selected.handle, selected.service, selected.characteristic, parsedPayload, withResponse),
            )
        }
        root.emit("write", buildJsonObject { put("handle", selected.handle); put("length", parsedPayload.size); put("withResponse", withResponse) }, "Wrote ${parsedPayload.size} bytes to ${selected.handle}")
    }

    private fun payload(): ByteArray {
        val hex = hexPayload
        val base64 = base64Payload
        val text = textPayload
        val stdin = stdinEncoding
        val sourceCount = listOf(hex, base64, text, stdin).count { it != null }
        if (sourceCount != 1) throw CliFailure(ExitCode.USAGE, "Specify exactly one of --hex, --base64, --text, or --stdin")
        return when {
            hex != null -> decodeHex(hex)
            base64 != null -> decodeBase64(base64)
            text != null -> text.encodeToByteArray()
            else -> {
                val raw = readStandardInput(MAX_WRITE_STDIN_BYTES + 1)
                if (raw.size > MAX_WRITE_STDIN_BYTES) throw CliFailure(ExitCode.USAGE, "stdin write payload exceeds 64 KiB")
                when (stdin) {
                    "hex" -> decodeHex(raw.decodeToString())
                    "base64" -> decodeBase64(raw.decodeToString())
                    "text" -> raw
                    else -> error("write source was not selected")
                }
            }
        }
    }

    private companion object { const val MAX_WRITE_STDIN_BYTES = 64 * 1024 }
}

