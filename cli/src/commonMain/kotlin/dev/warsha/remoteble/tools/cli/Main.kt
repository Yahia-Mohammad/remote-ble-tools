/**
 * Refuses a command group invoked without one of its subcommands.
 *
 * Printing the usage text and stopping there is not enough: nothing says what went wrong, so the
 * reader gets a wall of help and has to infer it, and the text lands on stdout where a caller
 * piping the command receives help as data. The root also exited 2 while a group exited 0, which
 * told a script the run had succeeded when nothing had run at all.
 */
private fun CliktCommand.requireSubcommand() {
    if (currentContext.invokedSubcommand != null) return
    echo(getFormattedHelp(), err = true)
    echo("Error: no command given", err = true)
    throw ProgramResult(ExitCode.USAGE.value)
}

internal class RootCommand : CliktCommand(
    name = "remoteble",
) {
    private val global by GlobalOptions()
    private var active: EffectiveOptions? = null
    private var outputSequence: Long = 0
    private var copiedIdentityWarningEmitted = false

    init {
        versionOption("RemoteBLE CLI $CLI_VERSION")
        completionOption()
    }

    override fun run() {
        active = global.effectiveWith(null)
        requireSubcommand()
    }
    override fun help(context: Context): String = "A scriptable client for RemoteBLE agents."
    override val invokeWithoutSubcommand: Boolean = true

    private fun GlobalOptions.effectiveWith(local: GlobalOptions?): EffectiveOptions = EffectiveOptions(
        configPath = local?.configPath ?: configPath,
        profile = local?.profile ?: profile,
        endpoint = local?.endpoint ?: endpoint,
        clientId = local?.clientId ?: clientId,
        tokenStdin = tokenStdin || local?.tokenStdin == true,
        json = json || local?.json == true,
        jsonl = jsonl || local?.jsonl == true,
        quiet = quiet || local?.quiet == true,
        output = local?.output ?: output,
        logLevel = local?.logLevel ?: logLevel,
    )

    fun activate(local: GlobalOptions) {
        active = global.effectiveWith(local)
        val selected = checkNotNull(active)
        val selectedModes = listOf(selected.json, selected.jsonl, selected.quiet, selected.output != null).count { it }
        if (selectedModes > 1) throw CliFailure(ExitCode.USAGE, "Choose only one output mode")
    }

    private fun options(): EffectiveOptions = checkNotNull(active) { "CLI options have not been parsed" }

    fun config(): FileConfig = options().let {
        ConfigLoader.load(it.configPath, it.profile ?: environmentVariable("REMOTE_BLE_PROFILE")).first
    }

    fun resolvedConfig(): ResolvedConfig {
        val selected = options()
        val base = config().resolve(
            selected.endpoint ?: environmentVariable("REMOTE_BLE_ENDPOINT"),
            selected.clientId ?: environmentVariable("REMOTE_BLE_CLIENT_ID"),
        )
        if (!copiedIdentityWarningEmitted && base.agent.clientId?.let(::isAutoGeneratedClientIdentity) == true) {
            copiedIdentityWarningEmitted = true
            writeStandardError("remoteble: configured rble-auto client id appears copied; omit it to use this machine's persisted identity\n".encodeToByteArray())
        }
        return base.copy(
            scanDuration = environmentVariable("REMOTE_BLE_SCAN_DURATION")?.let(Duration::parse) ?: base.scanDuration,
            operationTimeout = environmentVariable("REMOTE_BLE_OPERATION_TIMEOUT")?.let(Duration::parse) ?: base.operationTimeout,
        )
    }

    fun auditLogger(): AuditLogger = AuditLogger(
        directory = environmentVariable("REMOTE_BLE_LOG_DIR") ?: config().defaults.logDirectory ?: AuditLogger.defaultLogDirectory(),
    )

    fun debugLoggingEnabled(): Boolean = (options().logLevel ?: environmentVariable("REMOTE_BLE_LOG_LEVEL") ?: config().defaults.logLevel).lowercase() == "debug"

    fun outputMode(): String = when {
        options().json -> "json"
        options().jsonl -> "jsonl"
        options().quiet -> "quiet"
        else -> options().output ?: environmentVariable("REMOTE_BLE_OUTPUT") ?: config().defaults.output
    }.lowercase()

    fun tokenFromStdinSelected(): Boolean = options().tokenStdin

    private fun operatorToken(config: FileConfig): String {
        val token = (config.agent.operatorTokenEnvironmentVariable?.let(::environmentVariable)
            ?: environmentVariable("REMOTE_BLE_OPERATOR_TOKEN"))
            ?: throw CliFailure(ExitCode.USAGE, "operator status requires REMOTE_BLE_OPERATOR_TOKEN or agent.operatorTokenEnvironmentVariable")
        val ordinary = environmentVariable(config.agent.tokenEnvironmentVariable)
        if (ordinary != null && ordinary == token) {
            throw CliFailure(ExitCode.USAGE, "operator and ordinary bearer credentials must be distinct")
        }
        return token
    }

    fun <T> gateway(operator: Boolean = false, action: suspend (RemoteBleGateway) -> T): T = runBlocking {
        val resolved = resolvedConfig()
        val ordinaryToken = if (options().tokenStdin) readTokenFromStdin() else null
        val operatorToken = if (operator) {
            operatorToken(config())
        } else {
            null
        }
        if (ordinaryToken != null && ordinaryToken == operatorToken) {
            throw CliFailure(ExitCode.USAGE, "operator and ordinary bearer credentials must be distinct")
        }
        val gateway = RemoteBleGateway.open(resolved, ordinaryToken, operatorToken)
        try {
            auditLogger().audit("remote.operation", endpoint = resolved.agent.endpoint, clientId = resolved.agent.clientId, result = "attempt")
            return@runBlocking action(gateway)
                .also { auditLogger().audit("remote.operation", endpoint = resolved.agent.endpoint, clientId = resolved.agent.clientId, result = "ok") }
        } catch (error: Throwable) {
            auditLogger().audit("remote.operation", endpoint = resolved.agent.endpoint, clientId = resolved.agent.clientId, result = "error", errorKind = error::class.simpleName)
            throw error
        } finally {
            gateway.close()
        }
    }

    fun openPersistentGateway(operator: Boolean = false): RemoteBleGateway = runBlocking {
        if (options().tokenStdin) {
            throw CliFailure(ExitCode.USAGE, "--token-stdin is unavailable for session and shell because stdin carries commands")
        }
        val resolved = resolvedConfig()
        val operatorToken = if (operator) {
            operatorToken(config())
        } else null
        RemoteBleGateway.open(resolved, operatorToken = operatorToken)
    }

    /**
     * Result data goes through the platform primitive rather than Clikt's `echo`, which reports no
     * write failure: a closed downstream pipe has to be observable here for the same reason it is in
     * the persistent session. Diagnostics stay on `echo(err = true)`, so stderr remains capturable
     * by the in-process command tests; stdout assertions belong in the packaged black-box tests.
     */
    private fun writeLine(text: String) = writeStandardOutput((text + "\n").encodeToByteArray())

    fun emit(type: String, value: JsonElement, human: String, quietValue: String? = null) {
        when (outputMode()) {
            "json" -> writeLine(codec.encodeToString(JsonElement.serializer(), envelope(type, value)))
            "jsonl" -> {
                outputSequence += 1
                writeLine(codec.encodeToString(JsonElement.serializer(), streamEnvelope(type, value)))
            }
            "quiet" -> quietValue?.let(::writeLine)
            "raw" -> quietValue?.encodeToByteArray()?.let(::writeStandardOutput)
            else -> writeLine(human)
        }
    }

    fun emitFailure(failure: CliFailure) {
        val structured = active?.let { runCatching { outputMode() }.getOrNull() in setOf("json", "jsonl") } == true
        if (structured) {
            val errorData = buildJsonObject {
                put("exitCode", failure.exitCode.value)
                put("message", failure.message)
                failure.agentError?.let { error ->
                    put("errorKind", error.kind.name)
                    error.gattStatus?.let { put("gattStatus", it) }
                    error.holder?.let { holder -> put("holder", buildJsonObject { put("principal", holder.principal); holder.clientId?.let { put("clientId", it) } }) }
                }
            }
            echo(
                codec.encodeToString(
                    JsonElement.serializer(),
                    if (outputMode() == "jsonl") { outputSequence += 1; streamEnvelope("error", errorData) } else envelope("error", errorData),
                ),
                err = true,
            )
        } else {
            echo("remoteble: ${failure.message}", err = true)
        }
    }

    fun emitBytes(type: String, bytes: ByteArray) {
        val mode = outputMode()
        if (mode == "raw") {
            writeStandardOutput(bytes)
            return
        }
        val encoded = if (mode == "base64") bytes.base64() else bytes.hex()
        emit(
            type,
            buildJsonObject {
                put("hex", bytes.hex())
                put("base64", bytes.base64())
                put("length", bytes.size)
            },
            encoded,
            encoded,
        )
    }

    fun require(caps: Set<String>, feature: AgentFeature, command: String) {
        if (!caps.supports(feature)) unsupportedFeature(feature, command)
    }

    private fun readTokenFromStdin(): String {
        val bytes = readStandardInput(MAX_TOKEN_BYTES + 1)
        if (bytes.size > MAX_TOKEN_BYTES) throw CliFailure(ExitCode.USAGE, "Token from stdin exceeds 8 KiB")
        val token = bytes.decodeToString().trim()
        if (token.isEmpty()) throw CliFailure(ExitCode.USAGE, "Token from stdin is empty")
        return token
    }

    private fun streamEnvelope(type: String, value: JsonElement) = buildJsonObject {
        put("schemaVersion", 1)
        put("type", type)
        put("timestamp", Clock.System.now().toString())
        put("sequence", outputSequence)
        put("data", value)
    }

    companion object {
        private const val MAX_TOKEN_BYTES = 8 * 1024
        private val codec = Json { prettyPrint = false; encodeDefaults = true }

        private fun envelope(type: String, value: JsonElement) = buildJsonObject {
            put("schemaVersion", 1)
            put("type", type)
            put("data", value)
        }

        fun failure(error: Throwable): CliFailure = operationFailure(error)
    }
}

internal abstract class RootChild(
    protected val root: RootCommand,
    name: String,
    private val commandHelp: String,
) : CliktCommand(name = name) {
    private val global by GlobalOptions()

    override fun help(context: Context): String = commandHelp

    protected fun execute(action: () -> Unit) {
        try {
            root.activate(global)
            action()
        } catch (result: ProgramResult) {
            throw result
        } catch (error: Throwable) {
            val failure = RootCommand.failure(error)
            root.emitFailure(failure)
            throw ProgramResult(failure.exitCode.value)
        }
    }
}

private class SkillsCommand : CliktCommand(name = "skills") {
    override fun run() = requireSubcommand()
    override fun help(context: Context): String = "Install and verify the bundled RemoteBLE Agent Skill locally."
    override val printHelpOnEmptyArgs: Boolean = true
