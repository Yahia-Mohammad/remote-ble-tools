    })
    put("slots", buildJsonObject { put("free", slots.free); put("total", slots.total) })
    put("connectedClients", connectedClients); put("otherLeases", otherLeases)
    put("leases", buildJsonArray { leases.forEach { lease -> add(buildJsonObject {
        put("handle", lease.handle); lease.name?.let { put("name", it) }; lease.holder?.let { put("holder", it) }; put("mine", lease.mine)
        put("connected", lease.connected); put("inGrace", lease.inGrace); lease.remainingGraceMs?.let { put("remainingGraceMs", it) }
    }) } })
}

/**
 * Agent-supplied strings reach a terminal here. `agentInfo`, lease handles, and holder names are
 * chosen elsewhere - by the agent, or by whoever holds a lease - so they get the same escaping as an
 * advertised device name rather than being trusted because they came from the agent.
 */
internal fun AgentStatusDto.human(): String = buildString {
    appendLine(escapeDeviceText(agentInfo) ?: "RemoteBLE agent")
    appendLine("slots: free=${slots.free} total=${slots.total} leases=${leases.size + otherLeases}")
    leases.forEach { lease ->
        appendLine(
            "lease: ${escapeDeviceText(lease.handle)} holder=${escapeDeviceText(lease.holder) ?: "hidden"} " +
                "connected=${lease.connected} grace=${lease.remainingGraceMs ?: 0}ms",
        )
    }
}.trimEnd()

private fun JsonObjectBuilder.put(key: String, value: Any?) {
    put(key, when (value) {
        null -> JsonNull
        is String -> JsonPrimitive(value)
        is Int -> JsonPrimitive(value)
        is Long -> JsonPrimitive(value)
        is Boolean -> JsonPrimitive(value)
        is Double -> JsonPrimitive(value)
        else -> error("Unsupported JSON primitive for $key: ${value::class.simpleName}")
    })
}
