private class ScanCommand(root: RootCommand) : RootChild(root, "scan", "Scan for BLE advertisements for a bounded duration.") {
    private val duration: String? by option("--duration", help = "Scan duration, e.g. 5s.")
    private val service: String? by option("--service", help = "Filter by advertised service UUID.")
    private val name: String? by option("--name", help = "Filter by advertised name.")
    private val minimumRssi: Int? by option("--minimum-rssi", help = "Local output filter; does not reduce radio work.").int()
    private val maximumEvents: Int by option("--max-events", help = "Maximum advertisements to collect.").int().default(100)

    override fun run() = execute {
        if (maximumEvents <= 0) throw CliFailure(ExitCode.USAGE, "--max-events must be positive")
        val filters = listOfNotNull(if (service != null || name != null) ScanFilter(service?.let(::normalizeUuid), name) else null)
        val deadline = duration?.let(Duration::parse) ?: root.resolvedConfig().scanDuration
        if (root.outputMode() == "jsonl") {
            root.gateway { gateway ->
                val scan = RemoteOperationService(gateway, root.resolvedConfig().agent.endpoint, root.auditLogger())
                    .managedScan(filters)
                var result = "complete"
                try {
                    result = collectBoundedStream(scan.events, maximumEvents, deadline) { ad ->
                        if (minimumRssi == null || ad.rssi >= minimumRssi!!) {
                            root.emit("scan.result", ad.json(), "${ad.device.value}\t${escapeDeviceText(ad.name).orEmpty()}\t${ad.rssi} dBm", ad.device.value)
                        }
                    }.reason.auditResult
                } catch (error: Throwable) {
                    result = "error"
                    throw error
                } finally {
                    kotlinx.coroutines.withContext(kotlinx.coroutines.NonCancellable) { runCatching { scan.stopAndAwait(result) } }
                }
            }
        } else {
            val ads = root.gateway { gateway ->
                RemoteOperationService(gateway, root.resolvedConfig().agent.endpoint, root.auditLogger())
                    .scan(filters, deadline, maximumEvents)
            }
                .filter { minimumRssi == null || it.rssi >= minimumRssi!! }
            val grouped = ads.withIndex().groupBy { it.value.device.value }
            val handles = grouped.keys.toList().sorted()
            val aggregate = handles.map { handle ->
                val indexed = grouped.getValue(handle)
                val first = indexed.first().value; val last = indexed.last().value
                buildJsonObject {
                    put("handle", handle); first.name?.let { put("name", escapeDeviceText(it)) }
                    put("rssi", last.rssi); put("eventCount", indexed.size); put("firstSeen", indexed.first().index); put("lastSeen", indexed.last().index)
                    put("serviceUuids", JsonArray(first.serviceUuids.map(::JsonPrimitive)))
                }
            }
            root.emit("scan", JsonArray(aggregate), handles.zip(aggregate).joinToString("\n") { (key, value) -> "$key\t${value["eventCount"]} events" }, handles.firstOrNull())
        }
    }
}

