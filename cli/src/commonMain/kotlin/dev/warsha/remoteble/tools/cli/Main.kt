private class CapabilitiesCommand(root: RootCommand) : RootChild(root, "capabilities", "Show the negotiated capability intersection.") {
    override fun run() = execute {
        val caps = root.gateway { it.capabilities().sorted() }
        val scanMode = caps.firstOrNull { it.startsWith("scan.concurrency.") }
            ?.removePrefix("scan.concurrency.") ?: "unknown"
        val data = buildJsonObject {
            put("capabilities", JsonArray(caps.map(::JsonPrimitive)))
            put("scanConcurrency", scanMode)
            put("handleTranslation", Capabilities.IDENTIFIER_TRANSLATION in caps)
        }
        root.emit(
            "agent.capabilities",
            data,
            (caps + "scan-concurrency=$scanMode").joinToString("\n"),
            caps.joinToString("\n"),
        )
    }
}

private class StatusCommand(root: RootCommand) : RootChild(root, "status", "Show official agent status when supported.") {
    private val operator: Boolean by option("--operator", help = "Use the configured operator token for full status details.").flag()
    override fun run() = execute {
        val status = root.gateway(operator) { gateway ->
            root.require(gateway.capabilities(), AgentFeature.STATUS, "agent status")
            RemoteOperationService(gateway, root.resolvedConfig().agent.endpoint, root.auditLogger()).status().also {
                if (operator && !it.operatorScope) {
                    throw CliFailure(ExitCode.AUTHENTICATION, "agent did not grant operator scope")
                }
            }
        }
        root.emit("agent.status", status.json(), status.human())
    }
}

