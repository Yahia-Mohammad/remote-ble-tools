private fun bytesJson(bytes: ByteArray): JsonObject = buildJsonObject {
    put("hex", bytes.hex())
    put("base64", bytes.base64())
    put("length", bytes.size)
}

private fun decodeHex(value: String): ByteArray {
    val normalized = value.trim()
    if (normalized.length % 2 != 0 || normalized.any { it.digitToIntOrNull(16) == null }) {
        throw CliFailure(ExitCode.USAGE, "--hex must contain an even number of hexadecimal digits")
    }
    return ByteArray(normalized.length / 2) { index ->
        ((normalized[index * 2].digitToInt(16) shl 4) or normalized[index * 2 + 1].digitToInt(16)).toByte()
    }
}

private fun decodeBase64(value: String): ByteArray = try {
    Base64.decode(value.trim())
} catch (_: IllegalArgumentException) {
    throw CliFailure(ExitCode.USAGE, "--base64 must contain valid Base64 data")
}

private fun AgentStatusDto.json(): JsonObject = buildJsonObject {
    agentInfo?.let { put("agentInfo", it) }; put("protocolVersion", protocolVersion); put("uptimeMs", uptimeMs); put("operatorScope", operatorScope)
    put("settings", buildJsonObject {
