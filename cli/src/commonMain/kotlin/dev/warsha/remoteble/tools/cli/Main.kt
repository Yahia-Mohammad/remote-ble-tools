private fun AdvertisementDto.json(): JsonObject = buildJsonObject {
    put("handle", device.value)
    name?.let { put("name", escapeDeviceText(it)) }
    put("rssi", rssi)
    put("serviceUuids", JsonArray(serviceUuids.map(::JsonPrimitive)))
