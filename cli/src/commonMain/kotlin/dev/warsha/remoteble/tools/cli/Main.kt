fun main(args: Array<String>) {
    val cli = buildCli()
    try {
        cli.parse(args)
    } catch (error: CliktError) {
        // `printHelpOnEmptyArgs` reports a missing command as a PrintHelpMessage that sets `error`,
        // but the type fixes `printError = false`, so Clikt would print the usage to stdout and
        // exit 0 -- telling a script the run succeeded when nothing ran. `error` is exactly the
        // distinction between help that was asked for and help that stands in for a refusal.
        if (error is PrintHelpMessage && error.error) {
            cli.getFormattedHelp(error)?.let { cli.echo(it, err = true) }
            cli.echo("Error: no command given", err = true)
            exitProcess(ExitCode.USAGE.value)
        }
        cli.echoFormattedHelp(error)
        exitProcess(if (error is UsageError) ExitCode.USAGE.value else error.statusCode)
    }
}

internal fun buildCli(): RootCommand {
    val root = RootCommand()
    val agent = AgentCommand().subcommands(
        CapabilitiesCommand(root),
        StatusCommand(root),
        SlotsCommand(root),
    )
    val descriptor = DescriptorCommand().subcommands(DescriptorReadCommand(root))
    val config = ConfigCommand().subcommands(ConfigShowCommand(root), ConfigValidateCommand(root))
    return root.subcommands(
        agent,
        ScanCommand(root),
        ConnectCommand(root),
        DisconnectCommand(root),
        InspectCommand(root),
        ReadCommand(root),
        descriptor,
        RssiCommand(root),
        ObserveCommand(root),
        WriteCommand(root),
        ReportCommand(root),
        SessionCommand(root),
        ShellCommand(root),
        config,
        SkillsCommand().subcommands(SkillInstallCommand(root), SkillDoctorCommand(root)),
    )
}

